package dev.skhanal.atrium.ui;

import android.content.Context;
import android.graphics.Bitmap;
import android.graphics.BitmapShader;
import android.graphics.Canvas;
import android.graphics.Matrix;
import android.graphics.Paint;
import android.graphics.RectF;
import android.graphics.Shader;
import android.text.TextPaint;
import android.text.TextUtils;
import android.view.View;

/**
 * One thing the TV can do, in the Tools row.
 *
 * The old launcher put these as four bare words along the bottom of the screen,
 * which looked like a debug menu left in by mistake. They are the same
 * destinations. What changed is that each one is now a panel with its own
 * light, a mark and a line saying what it does, so the utilities read as part
 * of the product rather than as something underneath it.
 *
 * The wash behind each chip is generated by the same code that builds the hero,
 * at chip size, so the whole screen is lit by one system.
 */
public final class ToolChip extends View {

    public static final float HEIGHT_DP = 56f;
    public static final float GAP_DP = 14f;
    private static final float CORNER_DP = 12f;
    private static final float PAD_DP = 13f;
    private static final float GLYPH_DP = 22f;
    private static final float TITLE_SP = 14f;
    private static final float SUB_SP = 11f;

    private final Paint fill = new Paint(Paint.ANTI_ALIAS_FLAG | Paint.FILTER_BITMAP_FLAG);
    private final Paint stroke = new Paint(Paint.ANTI_ALIAS_FLAG);
    private final Paint glyphPaint = new Paint(Paint.ANTI_ALIAS_FLAG);
    private final TextPaint titlePaint = new TextPaint(Paint.ANTI_ALIAS_FLAG);
    private final TextPaint subPaint = new TextPaint(Paint.ANTI_ALIAS_FLAG);
    private final RectF bounds = new RectF();
    private final Matrix shaderMatrix = new Matrix();

    private Bitmap wash;
    private BitmapShader shader;
    private String title = "";
    private String sub = "";
    private String titleCut = "";
    private String subCut = "";
    private int kind = Glyph.SETTINGS;
    private int accent = Palette.TEXT_PRIMARY;
    private int widthDp = 156;

    public ToolChip(Context context) {
        super(context);
        setFocusable(true);
        setFocusableInTouchMode(false);
        setWillNotDraw(false);
        setBackground(null);

        stroke.setStyle(Paint.Style.STROKE);
        stroke.setStrokeWidth(Dp.f(1.5f));
        titlePaint.setTypeface(Type.regular());
        titlePaint.setTextSize(Dp.sp(TITLE_SP));
        subPaint.setTypeface(Type.light());
        subPaint.setTextSize(Dp.sp(SUB_SP));

        setAlpha(0.92f);
    }

    public void set(String title, String sub, int glyphKind, int accent, Bitmap wash) {
        this.title = title == null ? "" : title;
        this.sub = sub == null ? "" : sub;
        this.kind = glyphKind;
        this.accent = accent;
        this.wash = wash;
        this.titleCut = "";
        this.subCut = "";
        if (wash != null) {
            shader = new BitmapShader(wash, Shader.TileMode.CLAMP, Shader.TileMode.CLAMP);
        }
        setContentDescription(this.title);
        invalidate();
    }

    public String title() {
        return title;
    }

    public String sub() {
        return sub;
    }

    public void setWidthDp(int dp) {
        this.widthDp = dp;
        requestLayout();
    }

    @Override
    protected void onMeasure(int widthSpec, int heightSpec) {
        setMeasuredDimension(Dp.of(widthDp), Dp.of(HEIGHT_DP));
    }

    @Override
    protected void onSizeChanged(int w, int h, int ow, int oh) {
        super.onSizeChanged(w, h, ow, oh);
        bounds.set(0, 0, w, h);
        setPivotX(w / 2f);
        setPivotY(h);
        titleCut = "";
        subCut = "";
    }

    @Override
    protected void onDraw(Canvas canvas) {
        float r = Dp.f(CORNER_DP);

        // The wash is painted through a shader rather than clipped, because a
        // clip path costs a save layer and this GPU charges for those.
        if (shader != null && wash != null) {
            shaderMatrix.reset();
            shaderMatrix.setScale(getWidth() / (float) wash.getWidth(),
                    getHeight() / (float) wash.getHeight());
            shader.setLocalMatrix(shaderMatrix);
            fill.setShader(shader);
        } else {
            fill.setShader(null);
            fill.setColor(0xFF15171D);
        }
        canvas.drawRoundRect(bounds, r, r, fill);
        fill.setShader(null);

        boolean on = isFocused();
        if (on) {
            float half = stroke.getStrokeWidth() / 2f;
            stroke.setColor(Palette.withAlpha(Palette.asRim(accent), 0.9f));
            bounds.inset(half, half);
            canvas.drawRoundRect(bounds, r - half, r - half, stroke);
            bounds.inset(-half, -half);
        }

        float gx = Dp.f(PAD_DP) + Dp.f(GLYPH_DP) / 2f;
        glyphPaint.setColor(on ? Palette.TEXT_PRIMARY : Palette.TEXT_SECONDARY);
        Glyph.draw(canvas, kind, gx, getHeight() / 2f, Dp.f(GLYPH_DP), glyphPaint);

        float textLeft = gx + Dp.f(GLYPH_DP) / 2f + Dp.f(11f);
        float avail = getWidth() - textLeft - Dp.f(10f);
        if (titleCut.isEmpty()) {
            titleCut = TextUtils.ellipsize(title, titlePaint, avail, TextUtils.TruncateAt.END).toString();
            subCut = TextUtils.ellipsize(sub, subPaint, avail, TextUtils.TruncateAt.END).toString();
        }

        titlePaint.setColor(Palette.TEXT_PRIMARY);
        subPaint.setColor(on ? Palette.TEXT_SECONDARY : Palette.TEXT_TERTIARY);

        Paint.FontMetrics tm = titlePaint.getFontMetrics();
        float titleBaseline = getHeight() / 2f - Dp.f(2f) - tm.descent;
        canvas.drawText(titleCut, textLeft, titleBaseline, titlePaint);
        Paint.FontMetrics sm = subPaint.getFontMetrics();
        canvas.drawText(subCut, textLeft, getHeight() / 2f + Dp.f(3f) - sm.ascent, subPaint);
    }

    public void applyFocus(boolean focused) {
        long d = Motion.d(Motion.FOCUS);
        float scale = focused ? 1.04f : 1f;
        float alpha = focused ? 1f : 0.92f;
        animate().cancel();
        if (d == 0) {
            setScaleX(scale);
            setScaleY(scale);
            setAlpha(alpha);
        } else {
            animate().scaleX(scale).scaleY(scale).alpha(alpha)
                    .setDuration(d).setInterpolator(Motion.SWIFT).start();
        }
        invalidate();
    }

    public void playPress() {
        long in = Motion.d(Motion.PRESS_IN);
        if (in == 0) {
            return;
        }
        animate().cancel();
        animate().scaleX(0.99f).scaleY(0.99f).setDuration(in)
                .setInterpolator(Motion.SMOOTH)
                .withEndAction(() -> animate().scaleX(1.04f).scaleY(1.04f)
                        .setDuration(Motion.d(Motion.PRESS_OUT))
                        .setInterpolator(Motion.SWIFT).start())
                .start();
    }
}
